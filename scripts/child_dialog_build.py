def article(word: str) -> str:
    return "an" if word[0] in "aeiou" else "a"


def plural(word: str) -> str:
    irregular = {
        "mouse": "mice",
        "sheep": "sheep",
        "fish": "fish",
        "deer": "deer",
        "wolf": "wolves",
        "goose": "geese",
        "polar bear": "polar bears",
        "octopus": "octopuses",
        "fox": "foxes",
        "fly": "flies",
        "butterfly": "butterflies",
        "lynx": "lynxes",
        "moose": "moose",
        "bison": "bison",
        "elk": "elk",
    }
    return irregular.get(word, word + "s")


def group(concept: dict) -> str | None:
    family, key = concept["family"], concept["key"]
    if family == "need":
        if key in NEED_DROP:
            return None
        return (
            "need_verb"
            if key in NEED_VERBS
            else "need_place"
            if key in NEED_PLACES
            else "need_thing"
        )
    if family == "place" and key in PLACE_DROP:
        return None
    if family == "feeling" and key in FEELING_HAVE:
        return "feeling_have"
    if family == "use" and key in PLURAL:
        return "use_plural"
    return family


def answer_word(answer: str) -> str:
    """The defining word(s) of a short answer: 'It is blue.' -> 'blue'."""
    text = answer.rstrip(".!").strip()
    for prefix in ("It is an ", "It is a ", "It is ", "It says "):
        if text.startswith(prefix):
            return text[len(prefix) :]
    return text.lower()


def answer_complement(answer: str) -> str:
    """Keep the article: 'It is a triangle.' -> 'a triangle'."""
    text = answer.rstrip(".!").strip()
    for prefix in ("It is ", "It says "):
        if text.startswith(prefix):
            text = text[len(prefix) :]
            break
    return text[:1].lower() + text[1:]


def fields(concept: dict) -> dict:
    key = concept["key"]
    many = key in PLURAL
    ans = concept["answer"]
    w = answer_word(ans)
    w_art = answer_complement(ans)
    ans_np = ans.rstrip(".!").strip()
    ans_np = ans_np[:1].lower() + ans_np[1:]
    out = {
        "k": key,
        "a": "" if many else article(key),
        "A": "" if many else article(key).capitalize(),
        "p": plural(key),
        "w": w,
        "W": w[:1].upper() + w[1:],
        "w_art": w_art,
        "W_art": w_art[:1].upper() + w_art[1:],
        "ans": ans,
        "ans_l": ans[:1].lower() + ans[1:],
        "ans_np": ans_np,
        "is": "are" if many else "is",
        "does": "do" if many else "does",
        "goes": "go" if many else "goes",
        "it": "them" if many else "it",
        "are": "are" if many else "is",
        "do": "do" if many else "does",
        "is_are": "are" if many else "is",
        "k_a": key if many else f"{article(key)} {key}",
        "K": key[:1].upper() + key[1:],
        "Ans": ans[:1].upper() + ans[1:],
    }
    if concept["family"] == "category":
        if key in CATEGORY_MASS:
            out |= {"a": "", "A": ""}
    elif key in MASS:
        if concept["family"] == "need":
            out |= {"a": "some", "A": "Some"}
        else:
            out |= {"a": "", "A": ""}
    if concept["family"] == "category":
        o1, o2 = concept["options"].split(" or a ")
        out |= {"o1": f"{article(o1)} {o1}", "o2": f"{article(o2)} {o2}"}
    if concept["family"] == "add":
        x, y = key.split()
        out |= {"x": x, "y": y, "X": x.capitalize()}
    if concept["family"] == "weather":
        statement = WEATHER[key]
        out |= {"s": statement, "S": statement[:1].upper() + statement[1:]}
    return out


def render(template: str, values: dict) -> str:
    text = template.format(**values)
    text = re.sub(r"\s+", " ", text).strip()
    # Answers can carry their own sentence punctuation.  Keep one mark, and do
    # not leave a full stop before a lowercase continuation ("socks. on").
    text = re.sub(r"([.!?])[.!?]+", r"\1", text)
    text = re.sub(r"\.(?=\s*[a-z])", "", text)
    # Never leave sentence punctuation next to a comma/semicolon/colon.
    text = re.sub(r"[.!?](?=[,;:])", "", text)
    text = re.sub(r"(?<=[,;:])[.!?]", "", text)
    text = (
        text.replace(" ,", ",").replace(" ?", "?").replace(" !", "!").replace(" .", ".")
    )
    return text[:1].upper() + text[1:]


def build(
    concepts: list[dict], seed: int, text_version: int = 1
) -> tuple[list, list, list]:
    if text_version == 1:
        frame_map, reply_map = FRAMES, REPLIES
        rng = random.Random(seed)
        held = {
            g: set(rng.sample(range(len(f)), HELD_OUT)) for g, f in frame_map.items()
        }
    elif text_version == 2:
        frame_map, reply_map = FRAMES_V2, REPLIES_V2
        held = {g: set(indexes) for g, indexes in HELD_V1.items()}
        rng = random.Random(seed)
        for g in NEW_GROUPS:
            held[g] = set(rng.sample(range(len(frame_map[g])), HELD_OUT))
    else:
        raise ValueError(f"unknown text version: {text_version}")
    frames = [
        {
            "group": g,
            "index": i,
            "template": t,
            "split": "test" if i in held[g] else "train",
        }
        for g, ts in frame_map.items()
        for i, t in enumerate(ts)
    ]
    kept, pairs = [], []
    for concept in concepts:
        g = group(concept)
        if g is None:
            continue
        values = fields(concept)
        reply_templates = (
            reply_map.get(g) or reply_map.get(concept["family"]) or ["{ans}"]
        )
        replies = list(dict.fromkeys(render(t, values) for t in reply_templates))
        kept.append({**concept, "group": g, "replies": replies})
        for index, template in enumerate(frame_map[g]):
            question = render(template, values)
            pairs.append(
                {
                    "id": f"{concept['id']}-f{index:02d}",
                    "concept": concept["id"],
                    "family": concept["family"],
                    "group": g,
                    "key": concept["key"],
                    "frame": index,
                    "question": question,
                    "answer": concept["answer"],
                    "replies": replies,
                    "split": "test" if index in held[g] else "train",
                }
            )
    return kept, frames, pairs


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--concepts",
        type=Path,
        default=None,
        help="concept JSONL; defaults to the v1 or v2 file for --text-version",
    )
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--seed", type=int, default=0)
    parser.add_argument(
        "--text-version",
        type=int,
        choices=(1, 2),
        default=1,
        help="1 keeps the original text set; 2 uses the extended v2 set",
    )
    args = parser.parse_args()
    concepts_path = args.concepts
    if concepts_path is None:
        name = f"child_dialog_concepts_v{args.text_version}.jsonl"
        concepts_path = Path(__file__).with_name(name)
    concepts = [json.loads(line) for line in concepts_path.read_text().splitlines()]
    kept, frames, pairs = build(concepts, args.seed, args.text_version)
    questions = [p["question"] for p in pairs]
    if len(questions) != len({q.lower() for q in questions}):
        raise ValueError("Two pairs share a question with different concepts")
    args.output.mkdir(parents=True, exist_ok=True)
    for name, rows in (("concepts", kept), ("frames", frames), ("pairs", pairs)):
        (args.output / f"{name}.jsonl").write_text(
            "".join(json.dumps(r) + "\n" for r in rows)
        )
    summary = {
        "concepts": len(kept),
        "frames": len(frames),
        "pairs": len(pairs),
        "test_pairs": sum(p["split"] == "test" for p in pairs),
        "by_family": {
            f: sum(c["family"] == f for c in kept)
            for f in sorted({c["family"] for c in kept})
        },
    }
    (args.output / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps(summary))


if __name__ == "__main__":
    main()
